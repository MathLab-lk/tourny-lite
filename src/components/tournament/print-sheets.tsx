'use client'

import { useAppStore } from '@/store/app-store'

/**
 * A4 print-only sheets. Rendered as a fixed overlay that is hidden on
 * screen and visible in print; everything else gets print:hidden.
 */
export function PrintSheets() {
  const printMode = useAppStore((s) => s.printMode)
  const detail = useAppStore((s) => s.detail)
  if (!printMode || !detail) return null

  const { tournament, divisions, games, events, standings, progress } = detail
  const divisionBy = (id: string) => divisions.find((d) => d.id === id)
  const gameBy = (id: string) => games.find((g) => g.id === id)

  return (
    <div className="fixed inset-0 z-[100] hidden bg-white text-black print:block">
      {printMode === 'progress' ? (
        <div className="p-6 print-p">
          <header className="mb-4 border-b-2 border-black pb-3 text-center">
            <h1 className="text-2xl font-black uppercase tracking-wide">{tournament.name}</h1>
            <p className="mt-0.5 text-sm">
              {tournament.organizer ? `${tournament.organizer} · ` : ''}M&amp;E Event Progress Sheet ·{' '}
              {new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' })}
            </p>
            <p className="mt-1 text-xs font-semibold">
              Completed {progress.completed} / {progress.total} events ({progress.percent}%) · Scoring: 1st {tournament.pointsFirst} / 2nd {tournament.pointsSecond} / 3rd {tournament.pointsThird} pts
            </p>
          </header>
          <table className="w-full border-collapse text-[10px]">
            <thead>
              <tr className="border-b border-black text-left">
                <th className="p-1.5 font-bold">#</th>
                <th className="p-1.5 font-bold">Division</th>
                <th className="p-1.5 font-bold">Game</th>
                <th className="p-1.5 font-bold">Event</th>
                <th className="p-1.5 font-bold">Status</th>
                <th className="p-1.5 font-bold">1st</th>
                <th className="p-1.5 font-bold">2nd</th>
                <th className="p-1.5 font-bold">3rd</th>
                <th className="p-1.5 font-bold">Recorded by</th>
                <th className="p-1.5 font-bold">Time</th>
              </tr>
            </thead>
            <tbody>
              {events.map((e, i) => {
                const d = divisionBy(e.divisionId)
                const g = gameBy(e.gameId)
                return (
                  <tr key={e.id} className="border-b border-gray-300">
                    <td className="p-1.5">{i + 1}</td>
                    <td className="p-1.5 font-semibold">Cat {d?.code ?? '—'}</td>
                    <td className="p-1.5">{g?.englishName ?? '—'}</td>
                    <td className="p-1.5 font-semibold">{e.subEventIndex}</td>
                    <td className="p-1.5 capitalize">{e.status.replace('_', ' ')}</td>
                    <td className="p-1.5 font-semibold">{e.result?.firstPlaceCode ?? '—'}</td>
                    <td className="p-1.5">{e.result?.secondPlaceCode ?? '—'}</td>
                    <td className="p-1.5">{e.result?.thirdPlaceCode ?? '—'}</td>
                    <td className="p-1.5">{e.result?.recordedBy ?? '—'}</td>
                    <td className="p-1.5">
                      {e.result ? new Date(e.result.recordedAt).toLocaleString([], { dateStyle: 'short', timeStyle: 'short' }) : '—'}
                    </td>
                  </tr>
                )
              })}
            </tbody>
          </table>
          <p className="mt-4 text-[9px] text-gray-600">
            Generated by Tourny Lite · {new Date().toLocaleString()}
          </p>
        </div>
      ) : (
        <div className="p-6 print-p">
          <header className="mb-5 border-b-2 border-black pb-3 text-center">
            <h1 className="text-2xl font-black uppercase tracking-wide">{tournament.name}</h1>
            <p className="mt-0.5 text-sm">
              {tournament.organizer ? `${tournament.organizer} · ` : ''}Center Awards Scorecard
            </p>
            <p className="mt-1 text-xs font-semibold">
              Final standings · 1st = {tournament.pointsFirst} pts · 2nd = {tournament.pointsSecond} pts · 3rd = {tournament.pointsThird} pts ·{' '}
              {progress.completed}/{progress.total} events completed
            </p>
          </header>
          <table className="w-full border-collapse text-xs">
            <thead>
              <tr className="border-b-2 border-black text-left">
                <th className="p-2 font-bold">Rank</th>
                <th className="p-2 font-bold">Center Code</th>
                <th className="p-2 font-bold">Center Name</th>
                <th className="p-2 text-center font-bold">1st (×{tournament.pointsFirst})</th>
                <th className="p-2 text-center font-bold">2nd (×{tournament.pointsSecond})</th>
                <th className="p-2 text-center font-bold">3rd (×{tournament.pointsThird})</th>
                <th className="p-2 text-right font-bold">Total Marks</th>
              </tr>
            </thead>
            <tbody>
              {standings.map((row) => (
                <tr key={row.centerId} className="border-b border-gray-300">
                  <td className="p-2 font-black">{row.rank}</td>
                  <td className="p-2 text-base font-black tabular-nums">{row.centerCode}</td>
                  <td className="p-2">{row.centerName || '—'}</td>
                  <td className="p-2 text-center font-semibold tabular-nums">{row.gold}</td>
                  <td className="p-2 text-center font-semibold tabular-nums">{row.silver}</td>
                  <td className="p-2 text-center font-semibold tabular-nums">{row.bronze}</td>
                  <td className="p-2 text-right text-base font-black tabular-nums">{row.total}</td>
                </tr>
              ))}
            </tbody>
          </table>
          <div className="mt-16 flex justify-between text-[10px] text-gray-700">
            <span>Prepared by: _______________________</span>
            <span>Verified by: _______________________</span>
            <span>Date: _______________________</span>
          </div>
          <p className="mt-6 text-[9px] text-gray-600">
            Tie-break order: total marks → gold count → silver count → bronze count · Generated {new Date().toLocaleString()}
          </p>
        </div>
      )}
    </div>
  )
}
