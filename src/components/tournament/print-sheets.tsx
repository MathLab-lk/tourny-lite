'use client'

import { createPortal } from 'react-dom'
import { useAppStore } from '@/store/app-store'
import { studentShortId } from '@/lib/student-math'

/**
 * A4 print sheets, rendered into a portal at the document root.
 *
 * The component only mounts while a print is in flight (printMode is
 * set only from a user interaction, so this can never run on the
 * server), and the `tourny-printing` class on <html> (set by the
 * store) hides every other body child for the duration — so the
 * printout contains the sheet and nothing else. On screen the root
 * stays hidden, so there is no flash before the print dialog opens.
 *
 * Two sheets exist: the event progress sheet and the student
 * ranking sheet (the full roster with ranks, centers and marks).
 */
export function PrintSheets() {
  const printMode = useAppStore((s) => s.printMode)
  const detail = useAppStore((s) => s.detail)

  if (!printMode || !detail || typeof document === 'undefined') return null

  const { tournament, divisions, games, events, progress } = detail

  if (printMode === 'students') {
    return createPortal(<StudentRankingSheet />, document.body)
  }

  const divisionBy = (id: string) => divisions.find((d) => d.id === id)
  const gameBy = (id: string) => games.find((g) => g.id === id)

  return createPortal(
    <div id="tourny-print-root" className="bg-white text-black">
      <div className="p-6 print-p">
        <header className="mb-4 border-b-2 border-black pb-3 text-center">
          <h1 className="text-2xl font-black uppercase tracking-wide">{tournament.name}</h1>
          <p className="mt-0.5 text-sm">
            {tournament.organizer ? `${tournament.organizer} · ` : ''}Event Progress Sheet ·{' '}
            {new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' })}
          </p>
          <p className="mt-1 text-xs font-semibold">
            Completed {progress.completed} / {progress.total} events ({progress.percent}%) · Scoring: 1st {tournament.pointsFirst} / 2nd {tournament.pointsSecond} / 3rd {tournament.pointsThird} pts
          </p>
        </header>
        <table className="w-full border-collapse text-[10px]">
          <thead>
            <tr className="border-b border-black text-left">
              <th className="p-1.5 font-bold">#</th>
              <th className="p-1.5 font-bold">Division</th>
              <th className="p-1.5 font-bold">Game</th>
              <th className="p-1.5 font-bold">Event</th>
              <th className="p-1.5 font-bold">Status</th>
              <th className="p-1.5 font-bold">1st</th>
              <th className="p-1.5 font-bold">2nd</th>
              <th className="p-1.5 font-bold">3rd</th>
              <th className="p-1.5 font-bold">Recorded by</th>
              <th className="p-1.5 font-bold">Time</th>
            </tr>
          </thead>
          <tbody>
            {events.map((e, i) => {
              const d = divisionBy(e.divisionId)
              const g = gameBy(e.gameId)
              return (
                <tr key={e.id} className="border-b border-gray-300">
                  <td className="p-1.5">{i + 1}</td>
                  <td className="p-1.5 font-semibold">Cat {d?.code ?? '—'}</td>
                  <td className="p-1.5">{g?.englishName ?? '—'}</td>
                  <td className="p-1.5 font-semibold">{e.subEventIndex}</td>
                  <td className="p-1.5 capitalize">{e.status.replace('_', ' ')}</td>
                  <td className="p-1.5 font-semibold">{e.result?.firstPlaceCode ?? '—'}</td>
                  <td className="p-1.5">{e.result?.secondPlaceCode ?? '—'}</td>
                  <td className="p-1.5">{e.result?.thirdPlaceCode ?? '—'}</td>
                  <td className="p-1.5">{e.result?.recordedBy ?? '—'}</td>
                  <td className="p-1.5">
                    {e.result ? new Date(e.result.recordedAt).toLocaleString([], { dateStyle: 'short', timeStyle: 'short' }) : '—'}
                  </td>
                </tr>
              )
            })}
          </tbody>
        </table>
        <p className="mt-4 text-[9px] text-gray-600">
          Generated by Tourny Lite · {new Date().toLocaleString()}
        </p>
      </div>
    </div>,
    document.body
  )
}

/**
 * The student ranking sheet — every registered student with their
 * rank, center, event count, best single mark and total. Students
 * sharing a name carry the short internal id so two "Kasun Perera"
 * rows can never be confused on paper.
 */
function StudentRankingSheet() {
  const detail = useAppStore((s) => s.detail)
  if (!detail) return null
  const { tournament, students, studentStandings } = detail
  const scored = studentStandings.filter((s) => s.events > 0).length

  // Names that appear more than once — their rows carry the short id.
  const counts = new Map<string, number>()
  for (const s of students) counts.set(s.name, (counts.get(s.name) ?? 0) + 1)
  const duplicates = new Set([...counts.entries()].filter(([, n]) => n > 1).map(([n]) => n))

  return createPortal(
    <div id="tourny-print-root" className="bg-white text-black">
      <div className="p-6 print-p">
        <header className="mb-4 border-b-2 border-black pb-3 text-center">
          <h1 className="text-2xl font-black uppercase tracking-wide">{tournament.name}</h1>
          <p className="mt-0.5 text-sm">
            {tournament.organizer ? `${tournament.organizer} · ` : ''}Student Ranking Sheet ·{' '}
            {new Date().toLocaleDateString(undefined, { year: 'numeric', month: 'long', day: 'numeric' })}
          </p>
          <p className="mt-1 text-xs font-semibold">
            {students.length} registered · {scored} scored · ranking by total marks
          </p>
        </header>
        <table className="w-full border-collapse text-[11px]">
          <thead>
            <tr className="border-b border-black text-left">
              <th className="p-1.5 font-bold">Rank</th>
              <th className="p-1.5 font-bold">Student</th>
              <th className="p-1.5 font-bold">Center</th>
              <th className="p-1.5 text-center font-bold">Events</th>
              <th className="p-1.5 text-center font-bold">Best mark</th>
              <th className="p-1.5 text-right font-bold">Total marks</th>
            </tr>
          </thead>
          <tbody>
            {studentStandings.map((row) => (
              <tr key={row.studentId} className="border-b border-gray-300">
                <td className="p-1.5 font-semibold">{row.events > 0 ? row.rank : '—'}</td>
                <td className="p-1.5 font-semibold">
                  {row.name}
                  {duplicates.has(row.name) ? (
                    <span className="ml-1 font-mono text-[9px] text-gray-600">{studentShortId(row.studentId)}</span>
                  ) : null}
                </td>
                <td className="p-1.5">{row.centerCode ?? '—'}</td>
                <td className="p-1.5 text-center">{row.events > 0 ? row.events : '—'}</td>
                <td className="p-1.5 text-center">{row.events > 0 ? row.best : '—'}</td>
                <td className="p-1.5 text-right font-semibold">{row.events > 0 ? row.total : '—'}</td>
              </tr>
            ))}
            {studentStandings.length === 0 ? (
              <tr>
                <td colSpan={6} className="p-6 text-center text-gray-500">
                  No students registered yet.
                </td>
              </tr>
            ) : null}
          </tbody>
        </table>
        <p className="mt-3 text-[9px] text-gray-600">
          Ties on totals break by events entered, then best single mark · Generated by Tourny Lite ·{' '}
          {new Date().toLocaleString()}
        </p>
      </div>
    </div>,
    document.body
  )
}
