/**
 * Regenerates src/lib/card-fonts.ts — the per-character advance-width
 * table the share cards use to fit and shrink text (see share-card.ts).
 *
 * The measurements come from fontkit, which is not a runtime dependency:
 * run this from a scratch directory with it installed, e.g.
 *
 *   mkdir -p /tmp/fontmeasure && cd /tmp/fontmeasure && bun add fontkit
 *   bun /path/to/tourny-lite/scripts/measure-font-widths.ts
 */
import { openSync, readSync, closeSync, statSync } from 'node:fs'
import fontkit from 'fontkit'

function load(path: string) {
  const fd = openSync(path, 'r')
  const size = statSync(path).size
  const buf = Buffer.alloc(size)
  readSync(fd, buf, 0, size, 0)
  closeSync(fd)
  return fontkit.create(buf)
}

const DIR = new URL('../public/fonts', import.meta.url).pathname
const FONTS: Record<string, string> = {
  regular: `${DIR}/Poppins-Regular.ttf`,
  medium: `${DIR}/Poppins-Medium.ttf`,
  semibold: `${DIR}/Poppins-SemiBold.ttf`,
}

// Latin-1 + punctuation we may print
const latinChars: string[] = []
for (let c = 0x20; c <= 0x7e; c++) latinChars.push(String.fromCharCode(c))
for (const c of '—–·…’‘“”×') latinChars.push(c)

// Sinhala block + digits (approximate — advances only, shaping may merge)
const siChars: string[] = []
for (let c = 0x0d80; c <= 0x0dff; c++) siChars.push(String.fromCharCode(c))
for (let c = 0x30; c <= 0x39; c++) siChars.push(String.fromCharCode(c))
siChars.push(' ', '-', '·', '(', ')')

const out: string[] = []
out.push('// Generated by scripts/measure-font-widths.ts (fontkit advance widths,')
out.push('// normalized to em units) — used to fit/shrink text on share cards.')
out.push('// Do not edit by hand; re-run the generator after changing fonts.')
out.push('')
out.push('export type CardFontWeight = \'regular\' | \'medium\' | \'semibold\'')
out.push('')
for (const [name, path] of Object.entries(FONTS)) {
  const font = load(path)
  const unitsPerEm = (font as any).unitsPerEm as number
  const widths: Record<string, number> = {}
  for (const ch of latinChars) {
    const glyph = (font as any).glyphsForString?.(ch)?.[0]
    if (!glyph) continue
    const w = glyph.advanceWidth / unitsPerEm
    if (w > 0) widths[ch] = Math.round(w * 1000) / 1000
  }
  const entries = Object.entries(widths)
    .map(([ch, w]) => `${JSON.stringify(ch)}:${w}`)
    .join(',')
  out.push(`const ${name.toUpperCase()}: Record<string, number> = {${entries}}`)
  out.push('')
}
// Sinhala advances (from Noto Sans Sinhala Regular)
const si = load(`${DIR}/NotoSansSinhala-Regular.ttf`)
const siUnits = (si as any).unitsPerEm as number
const siWidths: Record<string, number> = {}
for (const ch of siChars) {
  const glyph = (si as any).glyphsForString?.(ch)?.[0]
  if (!glyph) continue
  const w = glyph.advanceWidth / siUnits
  if (w > 0) siWidths[ch] = Math.round(w * 1000) / 1000
}
const siEntries = Object.entries(siWidths).map(([ch, w]) => `${JSON.stringify(ch)}:${w}`).join(',')
out.push(`const SINHALA: Record<string, number> = {${siEntries}}`)
out.push('')
out.push(`const LATIN: Record<CardFontWeight, Record<string, number>> = { regular: REGULAR, medium: MEDIUM, semibold: SEMIBOLD }`)
out.push('')
out.push(`/** Estimated advance width of \`text\` at \`size\` px (em-normalized table lookup). */`)
out.push(`export function measureText(text: string, weight: CardFontWeight, size: number): number {`)
out.push(`  let units = 0`)
out.push(`  for (const ch of text) {`)
out.push(`    units += LATIN[weight][ch] ?? SINHALA[ch] ?? 0.55`)
out.push(`  }`)
out.push(`  return units * size`)
out.push(`}`)
out.push('')
import { writeFileSync } from 'node:fs'
writeFileSync(new URL('../src/lib/card-fonts.ts', import.meta.url).pathname, out.join('\n'))
console.log('written src/lib/card-fonts.ts,', out.length, 'lines')

// Sanity: compare estimates against fontkit's real layout width for samples
const sb = load(FONTS.semibold)
for (const sample of ['Math Competition 2026', 'Bahugunaka Puwaruwa', 'Category B · Ages 9 to 10', '105']) {
  const run = (sb as any).layout(sample)
  const real = run.advanceWidth / (sb as any).unitsPerEm * 56
  const est = measureTextTsc(sample, 'semibold', 56)
  console.log(`  sample ${JSON.stringify(sample)}: fontkit=${real.toFixed(1)}px estimate=${est.toFixed(1)}px (${(((est - real) / real) * 100).toFixed(1)}%)`)
}
function measureTextTsc(text: string, weight: string, size: number): number {
  const map = weight === 'semibold' ? (load(FONTS.semibold) as any) : null
  let units = 0
  for (const ch of text) {
    const g = map.glyphsForString?.(ch)?.[0]
    units += g ? g.advanceWidth / map.unitsPerEm : 0.55
  }
  return units * size
}
